#!/usr/bin/env python3
"""Fixed, audited build-time PortableApps data layout selection.

The workflow input controls NEW profile placement, never migrates or removes data.
The Windows-mirror build still supports already populated b1r5 legacy profiles.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path

LAYOUTS = {
    True: 'windows-appdata-mirror-v2',
    False: 'legacy-profile-v1',
}


def parse_bool(value):
    if type(value) is bool:
        return value
    if isinstance(value, str) and value.lower() in ('true', 'false'):
        return value.lower() == 'true'
    raise ValueError('ARDIA_WINDOWS_STYLE_DATA must be exactly true or false')


def manifest_for(mirrored):
    if type(mirrored) is not bool:
        raise ValueError('Layout selection must be a Boolean')
    layout = LAYOUTS[mirrored]
    checksum = hashlib.sha256(layout.encode('ascii')).hexdigest()[:12]
    return {'schema': 1, 'windows_style_data': mirrored, 'layout': layout,
            'fingerprint': checksum}


def validate_manifest(manifest):
    if not isinstance(manifest, dict) or set(manifest) != {'schema', 'windows_style_data', 'layout', 'fingerprint'}:
        raise ValueError('Unknown layout manifest fields')
    if manifest['schema'] != 1 or manifest != manifest_for(manifest['windows_style_data']):
        raise ValueError('Layout manifest identity mismatch')
    return manifest


def load_manifest(path):
    return validate_manifest(json.loads(Path(path).read_text(encoding='utf-8')))


def header_for(manifest):
    validate_manifest(manifest)
    use_mirror = manifest['windows_style_data']
    return ('// Generated by scripts/data_layout.py from workflow checkbox.\n'
            '// Data migrations are NEVER automatic.\n'
            '#pragma once\n'
            'static constexpr bool ARDIA_PORTABLE_WINDOWS_DATA_LAYOUT = '
            + ('true' if use_mirror else 'false') + ';\n'
            'static constexpr const wchar_t* ARDIA_PORTABLE_LAYOUT_NAME = L"'
            + manifest['layout'] + '";\n')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--out', required=True)
    p.add_argument('--header', required=True)
    args = p.parse_args()
    data = manifest_for(parse_bool(os.environ.get('ARDIA_WINDOWS_STYLE_DATA', 'true')))
    output = Path(args.out); output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(data, ensure_ascii=True, indent=2) + '\n', encoding='utf-8')
    header = Path(args.header); header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text(header_for(data), encoding='utf-8')
    print('Selected data layout:', data['layout'], 'fingerprint:', data['fingerprint'])


if __name__ == '__main__':
    main()
