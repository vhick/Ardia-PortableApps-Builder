#!/usr/bin/env python3
"""Allowlisted GitHub Actions checkbox -> reproducible C++ launcher flags.

Never accepts arbitrary command line text: all emitted switches are fixed, audited
literals. A SHA256 fingerprint differentiates release variants for identical Ardia
binaries and builder revisions. The encryption toggle is opt-in, NOT recommended.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path

# name, exact flag, default, evidence category
FLAGS = (
    ('no_default_browser_check', '--no-default-browser-check', True, 'Chromium default-browser prompt'),
    ('disable_background_mode', '--disable-background-mode', True, 'Chromium background mode; not a shutdown guarantee'),
    ('disable_logging', '--disable-logging', True, 'Chromium logging switch'),
    ('disable_breakpad', '--disable-breakpad', True, 'Chromium crash reporter switch'),
    ('disable_machine_id', '--disable-machine-id', True, 'Not verified for Ardia; may be ignored'),
    ('disable_ardia_update', '--disable-ardia-update', True, 'Not verified for Ardia; not an updater guarantee'),
    ('disable_encryption_win', '--disable-encryption-win', False, 'UNVERIFIED and unsafe for credential protection; explicit opt-in only'),
)
KEYS = tuple(x[0] for x in FLAGS)
DEFAULTS = {name: default for name, _arg, default, _status in FLAGS}


def parse_bool(value, name):
    if isinstance(value, bool):
        return value
    if isinstance(value, str) and value.lower() in ('true', 'false'):
        return value.lower() == 'true'
    raise ValueError('Expected true/false for ' + name)


def from_environment(env):
    return {name: parse_bool(env.get('ARDIA_OPT_' + name.upper(),
                                 'true' if default else 'false'), name)
            for name, _arg, default, _status in FLAGS}


def manifest_for(selection):
    if set(selection) != set(KEYS):
        raise ValueError('Option names differ from the fixed launcher allowlist')
    if any(type(selection[key]) is not bool for key in KEYS):
        raise ValueError('Every launcher option must be a true Boolean')
    ordered = {name: selection[name] for name in KEYS}
    serialized = json.dumps(ordered, sort_keys=True, separators=(',', ':'), ensure_ascii=True)
    fingerprint = hashlib.sha256(serialized.encode('ascii')).hexdigest()[:12]
    return {'schema': 1, 'options': ordered,
            'enabled_arguments': [arg for name, arg, _def, _status in FLAGS if ordered[name]],
            'fingerprint': fingerprint}


def validate_manifest(data):
    if not isinstance(data, dict) or set(data) != {'schema', 'options', 'enabled_arguments', 'fingerprint'}:
        raise ValueError('Invalid launcher option manifest fields')
    if data['schema'] != 1 or not isinstance(data['options'], dict):
        raise ValueError('Unsupported launcher option manifest')
    if data != manifest_for(data['options']):
        raise ValueError('Launcher manifest hash/argument/options mismatch')
    return data


def load_manifest(path):
    return validate_manifest(json.loads(Path(path).read_text(encoding='utf-8')))


def header_for(data):
    validate_manifest(data)
    args = data['enabled_arguments']
    # Adjacent wide string literals are concatenated by the C++ compiler. Values
    # are hardcoded only from FLAGS; never interpolated from user string input.
    literals = ''.join('    L" ' + arg + '"\n' for arg in args) or '    L""\n'
    return ('// Generated by scripts/launcher_options.py from workflow Boolean inputs.\n'
            '// WARNING: --disable-ardia-update and --disable-machine-id are unverified.\n'
            '// WARNING: --disable-encryption-win is explicit opt-in and may weaken credential security.\n'
            '// Identical options produce a stable fingerprint for release identity.\n'
            '#pragma once\n'
            'static constexpr const wchar_t* ARDIA_PORTABLE_DEFAULT_FLAGS =\n'
            + literals.rstrip('\n') + ';\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out', required=True, help='Immutable build options JSON manifest')
    p.add_argument('--header', required=True, help='Compiled launcher header to generate')
    a = p.parse_args()
    selection = from_environment(os.environ)
    data = manifest_for(selection)
    if selection['disable_encryption_win']:
        print('WARNING: User explicitly selected an unverified flag that may weaken Windows credential protection.', flush=True)
    for name, arg, default, status in FLAGS:
        print(('ENABLED ' if selection[name] else 'DISABLED') + ' ' + arg + ' | ' + status)
    dest = Path(a.out); dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    header = Path(a.header); header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text(header_for(data), encoding='utf-8')
    print('Ardia launcher options fingerprint:', data['fingerprint'])


if __name__ == '__main__':
    main()
